/* global process, Buffer, URL, console */
// node tools/dragon/pack.mjs <in.json> -> src/adapters/render/decor/dragonData.ts
import { readFileSync, writeFileSync } from 'node:fs';
const d = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const n = d.pos.length / 3;
const buf = Buffer.alloc(n * 6 + n * 3 + d.idx.length * 2);
let o = 0;
for (let i = 0; i < d.pos.length; i++) {
  const a = i % 3;
  const t = (d.pos[i] - d.min[a]) / (d.max[a] - d.min[a]);
  buf.writeUInt16LE(Math.round(t * 65535), o);
  o += 2;
}
for (const c of d.rgb) buf[o++] = c;
for (const i of d.idx) {
  buf.writeUInt16LE(i, o);
  o += 2;
}
const f = (v) => Number(v.toFixed(4));
writeFileSync(
  new URL('../../src/adapters/render/decor/dragonData.ts', import.meta.url),
  `// GENERATED by tools/dragon/pack.mjs from a TripoSR draft (tools/dragon/clean.py). Do not edit.\n` +
    `// Layout: ${n} verts x 3 uint16 (quantised to MIN..MAX), ${n} x 3 uint8 linear RGB, ${d.idx.length / 3} tris x 3 uint16.\n` +
    `export const DRAGON_VERTS = ${n};\nexport const DRAGON_TRIS = ${d.idx.length / 3};\n` +
    `export const DRAGON_MIN = [${d.min.map(f)}] as const;\nexport const DRAGON_MAX = [${d.max.map(f)}] as const;\n` +
    `export const DRAGON_B64 =\n  '${buf.toString('base64')}';\n`,
);
console.log('bytes', buf.length);
